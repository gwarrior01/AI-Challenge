//! Персонализация поверх модели памяти (см. [`crate::memory`]): вместо того
//! чтобы хранить манеру общения/язык ответа/ограничения как записи
//! долговременной памяти (раньше это делалось записью `agent remember ... key
//! value --category profile` — конвенция, а не отдельный механизм), профиль
//! теперь — это **отдельный markdown-файл** в каталоге профилей, не в SQLite.
//!
//! Мотивация та же, что и у разделения памяти на три уровня: у профиля своя
//! семантика (кто пользователь и как с ним говорить) и она не должна
//! перемешиваться с произвольными фактами/решениями долговременной памяти —
//! профиль редактируется человеком напрямую в текстовом редакторе (markdown, с
//! заголовками и примерами), а не через `key = value` пары.
//!
//! Каталог профилей — это первый из будущих подкаталогов конфигурации агента
//! (`profiles/` сейчас, возможно другие позже — по одному файлу на аспект
//! поведения агента); он не хранится в SQLite и не привязан к `AGENTS_STORE_PATH`,
//! потому что это конфигурация "с диска", предназначенная для правки руками, а
//! не результат работы агента.
//!
//! Один профиль может использоваться несколькими агентами одновременно (у
//! каждого агента в [`crate::agent::AgentConfig::profile`] хранится только имя
//! профиля, не его содержимое) — так несколько агентов, обслуживающих одного и
//! того же человека, говорят одним и тем же голосом без дублирования текста.

use anyhow::{bail, Context, Result};
use std::path::PathBuf;

/// Переменная окружения с путём к каталогу профилей — по аналогии с
/// `AGENTS_STORE_PATH` для реестра агентов.
pub const PROFILES_DIR_ENV: &str = "LLM_PROFILES_DIR";

/// Имя профиля, используемое по умолчанию, когда у агента не задано
/// [`crate::agent::AgentConfig::profile`] — файл `default.md` в каталоге профилей.
pub const DEFAULT_PROFILE: &str = "default";

/// Зарезервированное имя профиля, явно означающее "без персонализации" —
/// агент с `profile = Some("none")` не получает системный блок профиля в
/// запросе, даже если каталог профилей содержит файл `default.md`.
pub const NONE_PROFILE: &str = "none";

/// Каталог, где лежат markdown-файлы профилей — `LLM_PROFILES_DIR`, если задан,
/// иначе `profiles` в текущей рабочей директории.
pub fn profiles_dir() -> PathBuf {
    std::env::var(PROFILES_DIR_ENV).unwrap_or_else(|_| "profiles".to_string()).into()
}

/// `true`, если имя профиля — зарезервированное значение "none" (персонализация
/// явно выключена для агента с таким значением поля `profile`), без учёта регистра.
pub fn is_disabled(name: &str) -> bool {
    name.eq_ignore_ascii_case(NONE_PROFILE)
}

/// Разрешает значение [`crate::agent::AgentConfig::profile`] в конкретное имя
/// профиля: пустое/отсутствующее значение — [`DEFAULT_PROFILE`], иначе —
/// значение как есть (обрезанное от пробелов), включая [`NONE_PROFILE`].
pub fn resolve_name(configured: Option<&str>) -> String {
    match configured.map(str::trim) {
        Some(name) if !name.is_empty() => name.to_string(),
        _ => DEFAULT_PROFILE.to_string(),
    }
}

/// `true`, если строка годится в качестве имени файла профиля — непустая (после
/// обрезки пробелов), без разделителей пути и не `.`/`..`. Используется и при
/// чтении ([`load`]), и при создании ([`create`]) — во втором случае это не
/// просто гигиена, а защита от записи файла за пределами каталога профилей по
/// значению, которое ввёл человек (имя профиля, а не системный ключ).
fn is_valid_name(name: &str) -> bool {
    let name = name.trim();
    !name.is_empty() && !name.contains(['/', '\\']) && name != "." && name != ".."
}

/// Список имён всех профилей, найденных в каталоге профилей (файлы `*.md`,
/// без расширения, отсортированные) — пустой список, если каталога ещё нет.
pub fn list_profiles() -> Vec<String> {
    let dir = profiles_dir();
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return Vec::new();
    };
    let mut names: Vec<String> = entries
        .filter_map(|entry| entry.ok())
        .filter(|entry| entry.path().extension().and_then(|ext| ext.to_str()) == Some("md"))
        .filter_map(|entry| entry.path().file_stem().map(|s| s.to_string_lossy().into_owned()))
        .collect();
    names.sort();
    names
}

/// Читает содержимое профиля по имени — `None`, если имя — [`NONE_PROFILE`]
/// или файл `<name>.md` не найден в каталоге профилей (не ошибка: агент просто
/// работает без персонализации, как и с пустой долговременной/рабочей памятью).
pub fn load(name: &str) -> Option<String> {
    if is_disabled(name) || !is_valid_name(name) {
        return None;
    }
    let path = profiles_dir().join(format!("{name}.md"));
    std::fs::read_to_string(path).ok()
}

/// Шаблон нового профиля — те же разделы, что и у `profiles/default.md`, но
/// пустые, чтобы через интерфейс можно было завести профиль и сразу видеть,
/// что в нём заполнять, а не начинать с чистого листа.
pub fn template(name: &str) -> String {
    format!(
        "# Профиль: {name}\n\n\
         ## Стиль и манера общения\n\n- \n\n\
         ## Язык ответа\n\n- Отвечать на русском языке, если пользователь явно не попросил другой.\n\n\
         ## Формат ответа\n\n- \n\n\
         ## Ограничения\n\n- \n"
    )
}

/// Создаёт новый файл профиля `<name>.md` в каталоге профилей с заданным
/// содержимым — единственный способ добавить профиль ЧЕРЕЗ интерфейс (CLI/TUI/
/// web), а не правкой файла на диске руками. Ошибка, если имя пустое,
/// зарезервировано ([`NONE_PROFILE`]), содержит разделители пути/`.`/`..`
/// (см. [`is_valid_name`]) или файл с таким именем уже существует — создание
/// никогда не перезаписывает существующий профиль молча.
pub fn create(name: &str, content: &str) -> Result<()> {
    let name = name.trim();
    if name.is_empty() {
        bail!("имя профиля не может быть пустым");
    }
    if is_disabled(name) {
        bail!("«{NONE_PROFILE}» — зарезервированное имя (означает выключенную персонализацию), выберите другое");
    }
    if !is_valid_name(name) {
        bail!("имя профиля не должно содержать «/», «\\» и не может быть «.» или «..»");
    }
    let dir = profiles_dir();
    std::fs::create_dir_all(&dir)
        .with_context(|| format!("не удалось создать каталог профилей «{}»", dir.display()))?;
    let path = dir.join(format!("{name}.md"));
    if path.exists() {
        bail!("профиль «{name}» уже существует — отредактируйте файл {} напрямую", path.display());
    }
    std::fs::write(&path, content)
        .with_context(|| format!("не удалось записать файл профиля «{}»", path.display()))?;
    Ok(())
}

/// Форматирует содержимое профиля в системный блок для запроса к LLM — см.
/// [`crate::memory::format_long_term_block`] для аналогичного подхода у
/// долговременной памяти. Вызывающая сторона сама решает, добавлять ли этот
/// блок (см. [`crate::agent::Agent::handle_request`]) — ничего не подмешивается,
/// если [`load`] вернул `None`.
pub fn format_profile_block(name: &str, content: &str) -> String {
    format!(
        "Профиль пользователя «{name}» (стиль и манера общения, язык ответа, формат, ограничения — задан \
         отдельным markdown-файлом в каталоге профилей, подключается к КАЖДОМУ запросу этого агента, \
         независимо от стратегии контекста и от долговременной/рабочей памяти):\n\n{content}"
    )
}
